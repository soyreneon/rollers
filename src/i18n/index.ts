const translations: Record<Language, Translations> = { en, es };

export function t(
  key: TranslationKey,
  params: Record<string, string | number> = {},
): string {
  return translations[appConfig.language][key].replace(
    /\{(\w+)\}/g,
    (placeholder, name: string) => String(params[name] ?? placeholder),
  );
}
